// Draws the nookling mark as pixel art, with the app's own pixel renderer
// (src/pixel/raster.ts), into assets/icon-source.svg and public/favicon.svg.
// Run with `node scripts/pixel-mark.mjs`, then `npm run icons`.
//
// The mark is one colour (style.md §14: accent-amber on the Dusk ground) with
// the face cut out, so the monochrome themed icon keeps it.

import { writeFile } from "node:fs/promises";
import { createServer } from "vite";

const AMBER = "#d4a574"; // dusk-dawn-allow-colour: the icon is rendered outside the app, from the Dusk tokens
const GROUND = "#0f0d0b"; // dusk-dawn-allow-colour: Dusk --bg-grad-mid

const server = await createServer({
  server: { middlewareMode: true },
  appType: "custom",
  logLevel: "error",
});
try {
  const { render } = await server.ssrLoadModule("/src/pixel/raster.ts");
  const { BODY, EYE, fluffPath } = await server.ssrLoadModule(
    "/src/pet/geometry.ts",
  );
  const k = 1.86;
  const at = { x: 256, y: 268, s: k };
  const e = (cx, cy, rx, ry) => ({ e: [cx, cy, rx, ry], at });
  const layers = [
    {
      fill: AMBER,
      shapes: [
        { d: fluffPath(BODY.r, BODY.bumps, BODY.depth, BODY.ruffle), at },
        e(-30, 80, 17, 9),
        e(30, 80, 17, 9),
      ],
    },
    { fill: AMBER, cut: true, shapes: [{ r: [-6, 76, 12, 20], at }] },
    {
      fill: AMBER,
      cut: true,
      shapes: [
        e(-EYE.x, EYE.y + 2, 17, 21),
        e(EYE.x, EYE.y + 2, 17, 21),
        { d: "M-12 26Q0 29 12 26Q10 41 0 41Q-10 41 -12 26Z", at },
      ],
    },
    {
      fill: AMBER,
      shapes: [
        e(-EYE.x - 6, EYE.y - 6, 5.5, 6),
        e(EYE.x - 6, EYE.y - 6, 5.5, 6),
      ],
    },
  ];
  const runs = render(
    { layers, outline: "none" },
    { x: 96, y: 96, w: 320, h: 320, u: 8 },
  );
  const mark = runs
    .map(
      (r) => `<path fill="${AMBER}" shape-rendering="crispEdges" d="${r.d}"/>`,
    )
    .join("");
  const svg = (
    what,
  ) => `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
  <!-- Master icon (style.md §14: the Dusk bg-grad-mid ground, a mark in
       accent-amber, a 1px amber hairline frame), ${what}: #disk is the
       backdrop, #mark the nookling as pixel art, its eyes and smile cut out
       so the monochrome (themed) icon keeps its face. Generated by
       scripts/pixel-mark.mjs. -->
  <g id="disk">
    <rect width="512" height="512" fill="${GROUND}"/>
    <rect x="40" y="40" width="432" height="432" fill="none" stroke="${AMBER}" stroke-width="2" opacity="0.6"/>
  </g>
  <g id="mark">${mark}</g>
</svg>
`;
  await writeFile(
    "assets/icon-source.svg",
    svg("rendered to every launcher asset by `npm run icons`"),
  );
  await writeFile(
    "public/favicon.svg",
    svg("this copy is the browser tab icon"),
  );
  console.log("assets/icon-source.svg, public/favicon.svg");
} finally {
  await server.close();
}
